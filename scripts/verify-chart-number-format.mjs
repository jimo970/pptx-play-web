import assert from 'node:assert/strict'
import { formatChartNumber, formatChartNumberWithColor, getChartDateAxisMajorTicks, isSupportedChartNumberFormat } from '../app/utils/chart-number-format.ts'

assert.equal(isSupportedChartNumberFormat('0;(0)'), true)
assert.equal(formatChartNumber(12, '0;(0)'), '12')
assert.equal(formatChartNumber(-12, '0;(0)'), '(12)')
assert.equal(isSupportedChartNumberFormat('[>100]0.0;0.00'), true)
assert.equal(formatChartNumber(101, '[>100]0.0;0.00'), '101.0')
assert.equal(formatChartNumber(100, '[>100]0.0;0.00'), '100.00')
assert.equal(formatChartNumber(-20, '[>100]0.0;0.00'), '-20.00')
assert.equal(isSupportedChartNumberFormat('[>100]0.0;[<=-100]0.0;0.00'), true)
assert.equal(formatChartNumber(101, '[>100]0.0;[<=-100]0.0;0.00'), '101.0')
assert.equal(formatChartNumber(-101, '[>100]0.0;[<=-100]0.0;0.00'), '-101.0')
assert.equal(formatChartNumber(100, '[>100]0.0;[<=-100]0.0;0.00'), '100.00')
assert.equal(formatChartNumber(-99.9, '[>100]0.0;[<=-100]0.0;0.00'), '-99.90')
assert.equal(formatChartNumber(5, '[=5]0;[<>5]0.0;0.00'), '5')
assert.equal(formatChartNumber(4, '[=5]0;[<>5]0.0;0.00'), '4.0')
assert.equal(isSupportedChartNumberFormat('[>=1]0.0;[<=0]0.00'), false)
assert.equal(isSupportedChartNumberFormat('[>100]0.0;[<-100]0.0'), false)
assert.equal(isSupportedChartNumberFormat('[Red][>100]0;0'), true)
assert.deepEqual(formatChartNumberWithColor(101, '[Red][>100]0;0'), { text: '101', color: '#ff0000' })
assert.deepEqual(formatChartNumberWithColor(100, '[Red][>100]0;0'), { text: '100' })
assert.equal(isSupportedChartNumberFormat('[Red][<=100]0;[Blue][>100]0'), true)
assert.deepEqual(formatChartNumberWithColor(100, '[Red][<=100]0;[Blue][>100]0'), { text: '100', color: '#ff0000' })
assert.deepEqual(formatChartNumberWithColor(101, '[Red][<=100]0;[Blue][>100]0'), { text: '101', color: '#0000ff' })
assert.deepEqual(formatChartNumberWithColor(5, '[Red][<0]0;[Blue][>10]0'), { text: '5' })
assert.deepEqual(formatChartNumberWithColor(-12, '0;[Red](0)'), { text: '(12)', color: '#ff0000' })
assert.deepEqual(formatChartNumberWithColor(40729, '[Green]m/d/yyyy'), { text: '7/5/2011', color: '#008000' })
assert.deepEqual(formatChartNumberWithColor(12, '[Color1]0'), { text: '12', color: '#000000' })
assert.deepEqual(formatChartNumberWithColor(12, '[Color2]0'), { text: '12', color: '#ffffff' })
assert.deepEqual(formatChartNumberWithColor(12, '[Color3]0'), { text: '12', color: '#ff0000' })
assert.deepEqual(formatChartNumberWithColor(12, '[Color56]0'), { text: '12', color: '#333333' })
assert.equal(isSupportedChartNumberFormat('[Color56]0'), true)
assert.equal(isSupportedChartNumberFormat('[Color0]0'), false)
assert.equal(isSupportedChartNumberFormat('[Color57]0'), false)
const indexedColorPalette = Array(64).fill('FF000000')
indexedColorPalette[8] = 'FF123456'
indexedColorPalette[63] = 'FFABCDEF'
assert.deepEqual(formatChartNumberWithColor(101, '[Color1][>100]0;[Color56]0', false, indexedColorPalette), { text: '101', color: '#123456' })
assert.deepEqual(formatChartNumberWithColor(40729, '[Color56]m/d/yyyy', false, indexedColorPalette), { text: '7/5/2011', color: '#abcdef' })
assert.equal(isSupportedChartNumberFormat('[>Infinity]0;0'), false)
assert.equal(isSupportedChartNumberFormat('# ?/?'), true)
assert.equal(formatChartNumber(1.5, '# ?/?'), '1 1/2')
assert.equal(formatChartNumber(1.2, '# ?/?'), '1 1/5')
assert.equal(formatChartNumber(1.001, '# ???/???').split('/')[1]?.trim(), '999')
assert.equal(formatChartNumber(0.5, '# ?/?'), '1/2')
assert.equal(formatChartNumber(1.5, '# ?/8'), '1 4/8')
assert.equal(isSupportedChartNumberFormat('# ?/999999'), true)
assert.equal(formatChartNumber(1.99, '# ?/8'), '2')
assert.equal(formatChartNumber(1.5, '?/?').trim(), '3/2')
assert.equal(formatChartNumber(-1.5, '# ?/?;(# ?/?)'), '(1 1/2)')
assert.equal(formatChartNumber(0.015, '0 ?/?%'), '1 1/2%')
assert.equal(formatChartNumber(1.25, '# ??/??').replaceAll('\u00a0', ' '), '1  1/ 4')
assert.equal(isSupportedChartNumberFormat('# ?/0'), false)
assert.equal(isSupportedChartNumberFormat('# ?/1000000'), false)
assert.equal(formatChartNumber(12, '0;0.0'), '12')
assert.equal(formatChartNumber(-12, '0;0.0'), '12.0')
assert.equal(formatChartNumber(12, '000'), '012')
assert.equal(formatChartNumber(-12, '0;(000)'), '(012)')
assert.equal(isSupportedChartNumberFormat('$#,##0.00'), true)
assert.equal(formatChartNumber(1234.5, '$#,##0.00'), '$1,234.50')
assert.equal(formatChartNumber(-1234.5, '$#,##0.00;($#,##0.00)'), '($1,234.50)')
assert.equal(formatChartNumber(1234.5, '"USD "#,##0.00'), 'USD 1,234.50')
assert.equal(formatChartNumber(1234.5, '#,##0.00" kg"'), '1,234.50 kg')
assert.equal(formatChartNumber(2, '"value; "0'), 'value; 2')
assert.equal(isSupportedChartNumberFormat('0.0,,"M"'), true)
assert.equal(formatChartNumber(12_200_000, '0.0,,"M"'), '12.2M')
assert.equal(formatChartNumber(12_200_000, '0.0,,;(0.0,,)'), '12.2')
assert.equal(formatChartNumber(12_000, '#,##0,'), '12')
assert.equal(formatChartNumber(12.34, '0.0,%'), '1.2%')
assert.equal(isSupportedChartNumberFormat('0.0,,E+00'), false)
assert.equal(isSupportedChartNumberFormat('0.00E+00'), true)
assert.equal(formatChartNumber(12_200_000, '0.00E+00'), '1.22E+07')
assert.equal(formatChartNumber(12_200_000, '#0.0E+0'), '12.2E+6')
assert.equal(formatChartNumber(0.00122, '0.00E+00'), '1.22E-03')
assert.equal(formatChartNumber(-12_200_000, '0.00E+00'), '-1.22E+07')
assert.equal(formatChartNumber(-12_200_000, '0.00E+00;(0.00E+00)'), '(1.22E+07)')
assert.equal(formatChartNumber(12_200_000, '0.00e-00'), '1.22e07')
assert.equal(formatChartNumber(0.01234, '0.00E+00%'), '1.23E+00%')
assert.equal(formatChartNumber(0, '0.00E+00'), '0.00E+00')
assert.equal(formatChartNumber(9.999, '0.00E+00'), '1.00E+01')
assert.equal(formatChartNumber(0, '0;(0);'), '')
assert.equal(isSupportedChartNumberFormat('0;[Red](0)'), true)
assert.equal(formatChartNumber(-12, '0;[Red](0)'), '(12)')
assert.equal(isSupportedChartNumberFormat('m/d/yyyy'), true)
assert.equal(isSupportedChartNumberFormat('yyyy-mm-dd;@'), true)
assert.equal(formatChartNumber(40729, 'm/d/yyyy'), '7/5/2011')
assert.equal(formatChartNumber(39267, 'm/d/yyyy', true), '7/5/2011')
assert.equal(formatChartNumber(60, 'm/d/yyyy'), '2/29/1900')
assert.equal(formatChartNumber(0.5, 'h:mm AM/PM'), '12:00 PM')
assert.equal(isSupportedChartNumberFormat('[h]:mm'), true)
assert.equal(formatChartNumber(1.5, '[h]:mm'), '36:00')
assert.equal(formatChartNumber(1.5, '[hh]:mm'), '36:00')
assert.equal(formatChartNumber(1.5, '[mm]:ss'), '2160:00')
assert.equal(formatChartNumber(1.5, '[ss]'), '129600')
assert.equal(isSupportedChartNumberFormat('[ss].00'), true)
assert.equal(formatChartNumber(0.500012345, 'h:mm:ss.00'), '12:00:01.07')
assert.equal(formatChartNumber(1.999999999, '[ss].00'), '172800.00')
assert.equal(isSupportedChartNumberFormat('[ss].0000'), true)
assert.equal(isSupportedChartNumberFormat('[ss].000000'), true)
assert.equal(formatChartNumber(0.500012345, 'h:mm:ss.0000'), '12:00:01.0666')
assert.equal(formatChartNumber(0.500012345, 'h:mm:ss.000000'), '12:00:01.066608')
assert.equal(formatChartNumber(1.999999999, '[ss].000000'), '172799.999914')
assert.equal(isSupportedChartNumberFormat('[hhh]:mm'), false)
assert.equal(isSupportedChartNumberFormat('[ss].0000000'), false)
assert.deepEqual(getChartDateAxisMajorTicks(39266, 39275, 2, 'days', true), [39266, 39268, 39270, 39272, 39274])
assert.deepEqual(getChartDateAxisMajorTicks(30, 120, 1, 'months', true), [30, 59, 90, 120])
assert.deepEqual(getChartDateAxisMajorTicks(60, 90, 1, 'months'), [60, 89])
assert.equal(getChartDateAxisMajorTicks(30, 120, 0.5, 'months', true), undefined)
assert.equal(getChartDateAxisMajorTicks(0, 1000, 1, 'days', true), undefined)

console.log('Chart number format checks passed.')
