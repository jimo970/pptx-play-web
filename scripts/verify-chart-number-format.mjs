import assert from 'node:assert/strict'
import { formatChartNumber, getChartDateAxisMajorTicks, isSupportedChartNumberFormat } from '../app/utils/chart-number-format.ts'

assert.equal(isSupportedChartNumberFormat('0;(0)'), true)
assert.equal(formatChartNumber(12, '0;(0)'), '12')
assert.equal(formatChartNumber(-12, '0;(0)'), '(12)')
assert.equal(formatChartNumber(12, '0;0.0'), '12')
assert.equal(formatChartNumber(-12, '0;0.0'), '12.0')
assert.equal(formatChartNumber(12, '000'), '012')
assert.equal(formatChartNumber(-12, '0;(000)'), '(012)')
assert.equal(isSupportedChartNumberFormat('$#,##0.00'), true)
assert.equal(formatChartNumber(1234.5, '$#,##0.00'), '$1,234.50')
assert.equal(formatChartNumber(-1234.5, '$#,##0.00;($#,##0.00)'), '($1,234.50)')
assert.equal(formatChartNumber(1234.5, '"USD "#,##0.00'), 'USD 1,234.50')
assert.equal(formatChartNumber(1234.5, '#,##0.00" kg"'), '1,234.50 kg')
assert.equal(formatChartNumber(2, '"value; "0'), 'value; 2')
assert.equal(isSupportedChartNumberFormat('0.0,,"M"'), true)
assert.equal(formatChartNumber(12_200_000, '0.0,,"M"'), '12.2M')
assert.equal(formatChartNumber(12_200_000, '0.0,,;(0.0,,)'), '12.2')
assert.equal(formatChartNumber(12_000, '#,##0,'), '12')
assert.equal(formatChartNumber(12.34, '0.0,%'), '1.2%')
assert.equal(isSupportedChartNumberFormat('0.0,,E+00'), false)
assert.equal(isSupportedChartNumberFormat('0.00E+00'), true)
assert.equal(formatChartNumber(12_200_000, '0.00E+00'), '1.22E+07')
assert.equal(formatChartNumber(12_200_000, '#0.0E+0'), '12.2E+6')
assert.equal(formatChartNumber(0.00122, '0.00E+00'), '1.22E-03')
assert.equal(formatChartNumber(-12_200_000, '0.00E+00'), '-1.22E+07')
assert.equal(formatChartNumber(-12_200_000, '0.00E+00;(0.00E+00)'), '(1.22E+07)')
assert.equal(formatChartNumber(12_200_000, '0.00e-00'), '1.22e07')
assert.equal(formatChartNumber(0.01234, '0.00E+00%'), '1.23E+00%')
assert.equal(formatChartNumber(0, '0.00E+00'), '0.00E+00')
assert.equal(formatChartNumber(9.999, '0.00E+00'), '1.00E+01')
assert.equal(formatChartNumber(0, '0;(0);'), '')
assert.equal(isSupportedChartNumberFormat('0;[Red](0)'), false)
assert.equal(formatChartNumber(-12, '0;[Red](0)'), '-12')
assert.equal(isSupportedChartNumberFormat('m/d/yyyy'), true)
assert.equal(isSupportedChartNumberFormat('yyyy-mm-dd;@'), true)
assert.equal(formatChartNumber(40729, 'm/d/yyyy'), '7/5/2011')
assert.equal(formatChartNumber(39267, 'm/d/yyyy', true), '7/5/2011')
assert.equal(formatChartNumber(60, 'm/d/yyyy'), '2/29/1900')
assert.equal(formatChartNumber(0.5, 'h:mm AM/PM'), '12:00 PM')
assert.equal(isSupportedChartNumberFormat('[h]:mm'), true)
assert.equal(formatChartNumber(1.5, '[h]:mm'), '36:00')
assert.equal(formatChartNumber(1.5, '[hh]:mm'), '36:00')
assert.equal(formatChartNumber(1.5, '[mm]:ss'), '2160:00')
assert.equal(formatChartNumber(1.5, '[ss]'), '129600')
assert.equal(isSupportedChartNumberFormat('[ss].00'), true)
assert.equal(formatChartNumber(0.500012345, 'h:mm:ss.00'), '12:00:01.07')
assert.equal(formatChartNumber(1.999999999, '[ss].00'), '172800.00')
assert.equal(isSupportedChartNumberFormat('[hhh]:mm'), false)
assert.equal(isSupportedChartNumberFormat('[ss].0000'), false)
assert.deepEqual(getChartDateAxisMajorTicks(39266, 39275, 2, 'days', true), [39266, 39268, 39270, 39272, 39274])
assert.deepEqual(getChartDateAxisMajorTicks(30, 120, 1, 'months', true), [30, 59, 90, 120])
assert.deepEqual(getChartDateAxisMajorTicks(60, 90, 1, 'months'), [60, 89])
assert.equal(getChartDateAxisMajorTicks(30, 120, 0.5, 'months', true), undefined)
assert.equal(getChartDateAxisMajorTicks(0, 1000, 1, 'days', true), undefined)

console.log('Chart number format checks passed.')
